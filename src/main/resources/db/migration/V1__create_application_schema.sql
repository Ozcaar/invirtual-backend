-- Initial schema aligned with the current JPA entities.
-- IF NOT EXISTS lets an existing installation adopt Flyway without dropping data.
CREATE TABLE IF NOT EXISTS app_user (
    user_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    supabase_id varchar(60) NOT NULL UNIQUE,
    name varchar(255) NOT NULL,
    full_name varchar(255),
    email varchar(255) NOT NULL,
    last_login timestamp without time zone,
    active boolean NOT NULL
);

CREATE TABLE IF NOT EXISTS role (
    role_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(255) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS user_role (
    user_id integer NOT NULL REFERENCES app_user(user_id),
    role_id integer NOT NULL REFERENCES role(role_id),
    assign_date timestamp without time zone,
    active boolean NOT NULL,
    PRIMARY KEY (user_id, role_id)
);

CREATE TABLE IF NOT EXISTS invitation_type (
    invitation_type_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(255) NOT NULL UNIQUE,
    description varchar(255)
);

CREATE TABLE IF NOT EXISTS guest_group (
    guest_group_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(255) NOT NULL UNIQUE,
    description varchar(255) NOT NULL
);

CREATE TABLE IF NOT EXISTS invitation_type_guest_group (
    guest_group_id integer NOT NULL REFERENCES guest_group(guest_group_id),
    invitation_type_id integer NOT NULL REFERENCES invitation_type(invitation_type_id),
    PRIMARY KEY (guest_group_id, invitation_type_id)
);

CREATE TABLE IF NOT EXISTS guest (
    guest_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    guest_group_id integer REFERENCES guest_group(guest_group_id),
    name varchar(255) NOT NULL,
    email varchar(255),
    confirmed_date timestamp without time zone,
    confirmed boolean,
    link_opened boolean,
    enabled boolean NOT NULL
);

CREATE TABLE IF NOT EXISTS invitation (
    invitation_uuid uuid PRIMARY KEY,
    invitation_type_id integer NOT NULL REFERENCES invitation_type(invitation_type_id),
    name varchar(255) NOT NULL,
    max_people integer NOT NULL,
    slug_url varchar(255) NOT NULL,
    confirmation_message varchar(255),
    creation_date timestamp without time zone NOT NULL,
    limit_date timestamp without time zone NOT NULL,
    is_demo boolean NOT NULL,
    active boolean NOT NULL
);

CREATE TABLE IF NOT EXISTS user_invitation (
    user_id integer NOT NULL REFERENCES app_user(user_id),
    invitation_uuid uuid NOT NULL REFERENCES invitation(invitation_uuid),
    created_at timestamp without time zone,
    PRIMARY KEY (user_id, invitation_uuid)
);

CREATE TABLE IF NOT EXISTS invitation_guest (
    invitation_uuid uuid NOT NULL REFERENCES invitation(invitation_uuid),
    guest_id integer NOT NULL REFERENCES guest(guest_id),
    guest_group_id integer NOT NULL REFERENCES guest_group(guest_group_id),
    PRIMARY KEY (invitation_uuid, guest_id, guest_group_id)
);

CREATE TABLE IF NOT EXISTS envelope (
    envelope_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    img_url varchar(255) NOT NULL
);

CREATE TABLE IF NOT EXISTS plan (
    id uuid PRIMARY KEY,
    code varchar(40) NOT NULL UNIQUE,
    name varchar(80) NOT NULL,
    description text,
    max_people integer NOT NULL,
    duration_days integer NOT NULL,
    features jsonb NOT NULL,
    active boolean NOT NULL,
    position integer,
    created_at timestamp with time zone NOT NULL,
    updated_at timestamp with time zone NOT NULL
);

CREATE TABLE IF NOT EXISTS plan_price (
    id uuid PRIMARY KEY,
    plan_id uuid NOT NULL REFERENCES plan(id),
    environment varchar(10) NOT NULL,
    currency varchar(3) NOT NULL,
    billing_type varchar(10) NOT NULL,
    stripe_price_id varchar(120) NOT NULL UNIQUE,
    active boolean NOT NULL,
    created_at timestamp with time zone NOT NULL,
    updated_at timestamp with time zone NOT NULL
);

CREATE TABLE IF NOT EXISTS plan_discount (
    id uuid PRIMARY KEY,
    plan_price_id uuid NOT NULL REFERENCES plan_price(id),
    name varchar(120) NOT NULL,
    public_code varchar(60),
    stripe_coupon_id varchar(120),
    stripe_promotion_code_id varchar(120),
    discount_type varchar(10),
    percent_off integer,
    amount_off integer,
    starts_at timestamp without time zone,
    ends_at timestamp without time zone,
    max_redemptions integer,
    new_customers_only boolean NOT NULL,
    priority integer NOT NULL,
    stackable boolean NOT NULL,
    active boolean NOT NULL,
    created_at timestamp with time zone NOT NULL,
    updated_at timestamp with time zone NOT NULL
);

CREATE TABLE IF NOT EXISTS plan_price_override (
    id uuid PRIMARY KEY,
    plan_price_id uuid NOT NULL REFERENCES plan_price(id),
    name varchar(120) NOT NULL,
    stripe_price_id_override varchar(120) NOT NULL UNIQUE,
    starts_at timestamp without time zone,
    ends_at timestamp without time zone,
    priority integer NOT NULL,
    active boolean NOT NULL,
    created_at timestamp with time zone NOT NULL,
    updated_at timestamp with time zone NOT NULL
);

CREATE TABLE IF NOT EXISTS orders (
    id uuid PRIMARY KEY,
    supabase_id varchar(80) NOT NULL,
    stripe_session_id varchar(120) NOT NULL UNIQUE,
    stripe_payment_intent_id varchar(120),
    stripe_price_id varchar(120) NOT NULL,
    amount_total bigint,
    currency varchar(3),
    status varchar(30) NOT NULL,
    created_at timestamp with time zone
);

CREATE TABLE IF NOT EXISTS entitlements (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id integer NOT NULL REFERENCES app_user(user_id),
    order_id uuid UNIQUE REFERENCES orders(id),
    max_people integer NOT NULL,
    duration_days integer NOT NULL,
    consumed_at timestamp without time zone,
    invitation_uuid uuid UNIQUE REFERENCES invitation(invitation_uuid)
);
